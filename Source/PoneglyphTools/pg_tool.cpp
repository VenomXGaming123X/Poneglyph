// pg_tool - Poneglyph command-line utility (portable, runs on Windows and Linux).
//   pg_tool pe <file>                         dump PE facts (arch, 4 GB flag, checksum, exports, imports)
//   pg_tool laa <exe> [--apply --backup-dir D] check / patch the Large Address Aware flag (with backup)
//   pg_tool hash <file>                       SHA-256
//   pg_tool gendef <systemD3D9> <out.def> [fallback.def]   generate the proxy export list with the REAL ordinals
//   pg_tool verify <proxy.dll> <systemD3D9>    Stage A/B static proof: arch, exports, ordinals, forwarders, engine id
#include "poneglyph/pe.hpp"
#include "poneglyph/sha256.hpp"
#include "poneglyph/util.hpp"
#include <cstdio>
#include <cstring>
#include <fstream>
#include <set>
using namespace pg;
static const char* kImplemented[]={"D3DPERF_BeginEvent","D3DPERF_EndEvent","D3DPERF_GetStatus","D3DPERF_QueryRepeatFrame","D3DPERF_SetMarker","D3DPERF_SetOptions",
 "D3DPERF_SetRegion","DebugSetLevel","DebugSetMute","Direct3D9EnableMaximizedWindowedModeShim","Direct3DCreate9","Direct3DCreate9Ex","Direct3DCreate9On12",
 "Direct3DCreate9On12Ex","Direct3DShaderValidatorCreate9","PSGPError","PSGPSampleTexture"};
static int cmdPe(const fs::path& f){
    auto p=inspectPe(f); if(!p.valid){ std::printf("INVALID: %s\n",p.error.c_str()); return 2; }
    std::printf("File        : %s (%s)\nArchitecture: %s\nType        : %s\n4 GB flag    : %s\nChecksum    : stored 0x%08X, calculated 0x%08X%s\nTimestamp   : %u\n",
      pathToUtf8(f).c_str(),formatBytes(p.fileSize).c_str(),p.archName().c_str(),p.isDll?"DLL":"EXE",p.laa?"ON (Large Address Aware)":"OFF",p.storedChecksum,p.calculatedChecksum,p.storedChecksum==0?" (0 = not used)":(p.storedChecksum==p.calculatedChecksum?" (match)":" (MISMATCH)"),p.timestamp);
    std::printf("Imports     : %s\n",join(p.importDlls,", ").c_str());
    std::printf("Exports     : %zu (ordinal base %u)\n",p.exports.size(),p.exportBase); for(auto& e:p.exports) std::printf("  %5u  %s%s%s\n",e.ordinal,e.name.c_str(),e.forwarded?" -> ":"",e.forwardTarget.c_str()); return 0;
}
static int cmdLaa(int argc,char** argv){
    if(argc<3) return 64; fs::path exe=pathFromUtf8(argv[2]); bool apply=false; fs::path bd=exe.parent_path()/"Poneglyph_Backups";
    for(int i=3;i<argc;i++){ if(!strcmp(argv[i],"--apply")) apply=true; else if(!strcmp(argv[i],"--backup-dir")&&i+1<argc) bd=pathFromUtf8(argv[++i]); }
    auto p=inspectPe(exe,{false,false,false}); if(!p.valid){ std::printf("Not a valid PE: %s\n",p.error.c_str()); return 2; }
    std::printf("%s: %s, 4 GB flag %s\n",pathToUtf8(exe.filename()).c_str(),p.archName().c_str(),p.laa?"ON":"OFF");
    if(!apply) return 0; auto r=patchLaa(exe,bd,{}); std::printf("%s\n",r.message.c_str()); return (r.result==LaaResult::Patched||r.result==LaaResult::AlreadyLaa)?0:3;
}
static int cmdGendef(const fs::path& sys,const fs::path& out,const fs::path& fallback){
    auto p=inspectPe(sys,{true,false,false}); std::set<std::string> impl(std::begin(kImplemented),std::end(kImplemented));
    bool ok=p.valid&&p.isDll; bool hasCreate=false; if(ok) for(auto& e:p.exports) if(e.name=="Direct3DCreate9") hasCreate=true;
    if(!ok||!hasCreate){
        std::fprintf(stderr,"pg_tool gendef: cannot use '%s' (%s). Using the fallback export list (names only).\n",pathToUtf8(sys).c_str(),p.valid?"no Direct3DCreate9":p.error.c_str());
        std::string t; if(fallback.empty()||!readFileText(fallback,t)){ std::fprintf(stderr,"fallback missing\n"); return 1; } return writeFileAtomic(out,t)?0:1; }
    std::string o="; GENERATED by pg_tool gendef from "+pathToUtf8(sys)+"\n; Names and ordinals mirror the genuine Windows d3d9.dll so ordinal imports resolve identically.\nLIBRARY d3d9\nEXPORTS\n";
    int n=0; for(auto& e:p.exports){ if(e.name.empty()) continue; if(impl.count(e.name)){ o+="  "+e.name+" @"+std::to_string(e.ordinal)+"\n"; n++; } else std::fprintf(stderr,"note: system export '%s' (ordinal %u) is not implemented by the engine; it is not exported.\n",e.name.c_str(),e.ordinal); }
    if(!writeFileAtomic(out,o)) return 1; std::printf("wrote %s (%d exports)\n",pathToUtf8(out).c_str(),n); return 0;
}
static int cmdVerify(const fs::path& proxy,const fs::path& sys){
    int fail=0; auto chk=[&](bool c,const std::string& m){ std::printf("  [%s] %s\n",c?"PASS":"FAIL",m.c_str()); if(!c) fail++; };
    auto a=inspectPe(proxy,{true,true,false}); auto s=inspectPe(sys,{true,false,false});
    chk(a.valid,"proxy is a valid PE file"); chk(s.valid,"system d3d9.dll is a valid PE file"); if(!a.valid||!s.valid) return 2;
    chk(a.isX86(),"proxy is x86 / PE32 ("+a.archName()+")"); chk(a.isDll,"proxy is a DLL"); chk(s.isX86(),"reference system d3d9.dll is x86 (use the SysWOW64 copy)");
    std::set<std::string> impl(std::begin(kImplemented),std::end(kImplemented)); std::set<std::string> have; for(auto& e:a.exports) have.insert(e.name);
    for(auto& e:s.exports){ if(!impl.count(e.name)) continue; bool found=false;
        for(auto& x:a.exports) if(x.name==e.name){ found=true; chk(x.ordinal==e.ordinal,e.name+": ordinal "+std::to_string(x.ordinal)+(x.ordinal==e.ordinal?" matches system":" differs from system ordinal "+std::to_string(e.ordinal))); chk(!x.forwarded,e.name+": is a real function, not a forwarder (no recursion risk)"); }
        if(!found) chk(false,e.name+": MISSING from proxy"); }
    bool dc=have.count("Direct3DCreate9")>0; chk(dc,"Direct3DCreate9 exported");
    for(auto& d:a.importDlls) if(d=="d3d9.dll") chk(false,"proxy imports d3d9.dll by name (self-load risk)");
    std::string raw; readFileText(proxy,raw); chk(raw.find("PONEGLYPH_ENGINE_ID_7A3F")!=std::string::npos,"contains the Poneglyph engine id (manager can recognise it)");
    chk(raw.find("NovaFix")==std::string::npos&&raw.find("NOVAFIX")==std::string::npos,"contains no NovaFix strings (independent build)");
    std::printf("%s\n",fail?"RESULT: FAIL":"RESULT: PASS (static checks only - run pg_proxytest.exe on Windows for runtime forwarding)"); return fail?1:0;
}
int main(int argc,char** argv){
    if(argc<2){ std::printf("usage: pg_tool pe|laa|hash|gendef|verify ...\n"); return 64; }
    std::string c=argv[1];
    if(c=="pe"&&argc>=3) return cmdPe(pathFromUtf8(argv[2]));
    if(c=="laa") return cmdLaa(argc,argv);
    if(c=="hash"&&argc>=3){ std::string h; if(!Sha256::ofFile(pathFromUtf8(argv[2]),h)) return 2; std::printf("%s  %s\n",h.c_str(),argv[2]); return 0; }
    if(c=="gendef"&&argc>=4) return cmdGendef(pathFromUtf8(argv[2]),pathFromUtf8(argv[3]),argc>=5?pathFromUtf8(argv[4]):fs::path());
    if(c=="verify"&&argc>=4) return cmdVerify(pathFromUtf8(argv[2]),pathFromUtf8(argv[3]));
    std::printf("unknown or incomplete command\n"); return 64;
}
